// Regenerates supabase/migrations/0009_teaser_palettes.sql from src/content/teaser.ts.
// The output is plain ASCII (see q below), safe to copy-paste into the SQL Editor.
// Run: npx vite-node scripts/generate-teaser-palettes.ts
import { writeFileSync } from "node:fs";
import { allTeasers } from "@/content/teaser";

// Plain-ASCII SQL: Polish letters are written as \uXXXX escapes inside E'...'
// strings, so copying the file anywhere (clipboard, editors) can't garble them.
const q = (s: string) =>
  `E'${s
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "''")
    .replace(/[^\x20-\x7e]/gu, (ch) => {
      const code = ch.codePointAt(0)!;
      return code > 0xffff ? `\\U${code.toString(16).padStart(8, "0")}` : `\\u${code.toString(16).padStart(4, "0")}`;
    })}'`;
const rows = allTeasers().map((r) => `  (${q(r.eyes)}, ${q(r.hair)}, ${q(r.undertone)}, ${q(r.summary)}, ${q(JSON.stringify(r.colors))}::jsonb)`);

const sql = `-- Free teaser before payment: 4 hook colours for every combination of quiz
-- answers (eye colour x natural hair colour x undertone from the jewellery
-- answer). GENERATED by scripts/generate-teaser-palettes.ts; the app reads this
-- table (src/lib/api.ts getTeaser). Plain ASCII on purpose: Polish letters are
-- \\uXXXX escapes, so copy-pasting can't garble them.
-- Safe to re-run: it REPLACES all rows (edits made in the Table Editor are lost).
create table if not exists public.teaser_palettes (
  eyes text not null,
  hair text not null,
  undertone text not null check (undertone in (E'ciep\\u0142y', E'ch\\u0142odny', 'neutralny')),
  summary text not null,
  colors jsonb not null,
  primary key (eyes, hair, undertone)
);

-- Recreated so it always holds the correct Polish values (a garbled copy-paste
-- of an earlier version saved it with broken letters).
alter table public.teaser_palettes drop constraint if exists teaser_palettes_undertone_check;
delete from public.teaser_palettes;
alter table public.teaser_palettes add constraint teaser_palettes_undertone_check
  check (undertone in (E'ciep\\u0142y', E'ch\\u0142odny', 'neutralny'));

alter table public.teaser_palettes enable row level security;

-- Public, non-personal content: anyone may read, nobody may write via the API.
drop policy if exists "teaser palettes are public" on public.teaser_palettes;
create policy "teaser palettes are public"
  on public.teaser_palettes for select
  using (true);
revoke insert, update, delete on public.teaser_palettes from anon, authenticated;

insert into public.teaser_palettes (eyes, hair, undertone, summary, colors) values
${rows.join(",\n")}
on conflict (eyes, hair, undertone) do update
  set summary = excluded.summary, colors = excluded.colors;
`;
writeFileSync("supabase/migrations/0009_teaser_palettes.sql", sql);
console.log(`Wrote ${rows.length} rows`);
